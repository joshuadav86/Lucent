    /// <summary>Whether the dot in <paramref name="column"/> (0-4) and <paramref name="row"/> (0-6) of a character is lit. Characters it lacks show as '?'.</summary>
    public static bool IsLit(char character, int column, int row)
    {
        var index = character is >= ' ' and <= '~' ? character - ' ' : '?' - ' ';
        return ((Glyphs[index * 5 + column] >> row) & 1) != 0;
    }

    /// <summary>How wide <paramref name="text"/> is at <paramref name="scale"/>, in pixels (the last cell's gap left off).</summary>
    public static int Width(string text, int scale, int bold) =>
        text.Length == 0 ? 0 : (text.Length * CellWidth - 1) * scale + bold;

    /// <summary>How tall a line of text is at <paramref name="scale"/>, in pixels.</summary>
    public static int Height(int scale) => CellHeight * scale;

    /// <summary>
    /// Draws <paramref name="text"/> with its top-left at (<paramref name="left"/>, <paramref name="top"/>), each dot a square
    /// <paramref name="scale"/> pixels across (widened by <paramref name="bold"/> pixels for bold fonts), into <paramref name="buffer"/>.
    /// </summary>
    public static void Draw(int[] buffer, int width, int height, string text, int left, int top, int scale, int bold, int colour)
    {
        for (var i = 0; i < text.Length; i++)
        {
            var cellLeft = left + i * CellWidth * scale;
            if (cellLeft >= width || cellLeft + CellWidth * scale + bold <= 0)
            {
                continue;
            }

            for (var column = 0; column < 5; column++)
            {
                for (var row = 0; row < 7; row++)
                {
                    if (!IsLit(text[i], column, row))
                    {
                        continue;
                    }

                    var x0 = Math.Max(cellLeft + column * scale, 0);
                    var x1 = Math.Min(cellLeft + (column + 1) * scale + bold, width);
                    var y0 = Math.Max(top + row * scale, 0);
                    var y1 = Math.Min(top + (row + 1) * scale, height);
                    for (var y = y0; y < y1; y++)
                    {
                        Array.Fill(buffer, colour, y * width + x0, Math.Max(0, x1 - x0));
                    }
                }
            }
        }
    }
